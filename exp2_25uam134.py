# Define a sample messy string
phrase = " Learning Python is fun! "

print("Original Phrase:", repr(phrase))
print()

# 1. upper() & lower() - Case conversion
print("1. Upper Case:", phrase.upper())
print(" Lower Case:", phrase.lower())


# 2. strip() - Removes leading and trailing whitespaces
cleaned_phrase = phrase.strip()
print("2. Cleaned (strip):", repr(cleaned_phrase))


# 3. replace() - Replaces a substring with another
replaced_text = cleaned_phrase.replace("fun", "awesome")
print("3. Replaced Text:", replaced_text)


# 4. split() - Splits a string into a list based on a delimiter
word_list = cleaned_phrase.split(" ")
print("4.split into List:", word_list)


#5.join()-Merges a list of strings into one string
joined_text= "_".join(word_list)
print("%.Joined with Hyphen:", joined_text)


# 6. find() & index() - Searches for a substring and returns its index
print("6. Index of 'Python' (find):", cleaned_phrase.find("Python"))


# 7. count() - Counts occurrences of a substring
print("7. Count of letter 'n':", cleaned_phrase.count("n"))


# 8. startswith() & endswith() - Boolean validation checks
print("8. Starts with 'Learning'?:", cleaned_phrase.startswith("Learning"))
print(" Ends with '!'?:", cleaned_phrase.endswith("!"))


# 9. isalpha() & isdigit() - Character type checks
print("9. Is '12345' numeric?:", "12345".isdigit())
print(" Is 'Python' purely alphabetic?:", "Python".isalpha())

