#define sample string
text = "PythonProg"

#-----------------------------
#i. Accessing charraster by indexing
#-----------------------------

print("---1)String indexing---")

#positive indexing : starts from 0(Left to Right)
print("First character(Positive index 0):",text[0])
print("Sixth character(Positive index 5):",text[5])

#negative Indexing:Starts from -1(Right to Left)
print("Last character(Negative index -1):",text[-1])
print("Second to last character(Negative index -2):",text[-2])
print()



#-----------------------------------------
#ii. Accessing substring by slice operator
#syntax : string[start : stop : step]
#-----------------------------------------

print("---2)String slicing---")

#Basic slice(Extracts from index 0 up to 6, exclusive)
print("Slice[0:6]:", text[0:6])

#slicing with default start index (Omitting start default to 0)
print("Slice[:6]:", text[:6])

#slicing with default stop index (Omitting stop goes to end)
print("Slice[6:]:", text[6:])

# Slicing with negative indices
print("Slice [-4:-1]:", text[-4:-1])

# Slicing with a stride/step (Extracts every second character)
print("Slice [::2]:", text[::2])

# Reversing a string using a negative step
print("Reversed string [::-1]:", text[::-1])

